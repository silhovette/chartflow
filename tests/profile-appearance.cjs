const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto('http://127.0.0.1:4173');
    await page.locator('#guide [data-guide="close"]').click();
    await page.waitForFunction(() => !CF.guide.dialog.open);
    assert.equal(await page.locator('.user-chip small').count(), 0);
    await page.locator('.user-chip').click();
    const image = await page.evaluate(() => {
      const c = document.createElement('canvas'); c.width = 400; c.height = 300;
      const ctx = c.getContext('2d');
      ctx.fillStyle = '#328da8'; ctx.fillRect(0, 0, 400, 300);
      ctx.fillStyle = '#e9f9ff'; ctx.beginPath(); ctx.arc(200, 120, 55, 0, Math.PI * 2); ctx.fill();
      ctx.beginPath(); ctx.ellipse(200, 300, 110, 100, 0, 0, Math.PI * 2); ctx.fill();
      return c.toDataURL('image/png').split(',')[1];
    });
    const chooserPromise = page.waitForEvent('filechooser');
    await page.getByRole('button', { name: 'Avatar options', exact: true }).click();
    await page.locator('[data-account="avatar"]').click();
    await (await chooserPromise).setFiles({ name: 'avatar.png', mimeType: 'image/png', buffer: Buffer.from(image, 'base64') });
    await page.waitForSelector('#user-avatar img');
    await page.waitForFunction(() => !document.querySelector('#avatar-upload'));
    assert.equal(await page.locator('#user-avatar').evaluate(e => getComputedStyle(e).borderWidth), '0px');
    assert.equal(await page.locator('.profile-monogram').evaluate(e => getComputedStyle(e).borderWidth), '0px');
    await page.reload();
    await page.waitForSelector('#user-avatar img');
    await page.waitForFunction(() => CF.guide.dialog?.open);
    await page.evaluate(() => CF.guide.close());
    await page.waitForFunction(() => !CF.guide.dialog.open && !CF.guide.busy);
    assert.equal(await page.locator('#user-avatar img').evaluate(e => e.naturalWidth), 256);
    await page.evaluate(async () => {
      const bundle = await CF.storage.bundle();
      if (CF.account.parse(bundle).profile.avatar !== bundle.profile.avatar) throw Error('Avatar lost during import');
      const p = CF.progress.profile;
      for (const [id] of CF.progress.catalogue.slice(0, -1)) p.unlocked[id] = Date.now();
      p.unlocked.extra = Date.now();
      await CF.progress.save();
    });
    assert.equal(await page.locator('.all-achievements').count(), 0);
    await page.evaluate(async () => {
      const [, , , key, target] = CF.progress.catalogue.at(-1);
      CF.progress.profile.stats[key] = target;
      await CF.progress.save();
    });
    await page.waitForSelector('.user-chip.all-achievements');
    const angle = () => page.locator('.user-chip').evaluate(e => getComputedStyle(e, '::after').getPropertyValue('--aura-angle'));
    const start = await angle(); await page.waitForTimeout(250); assert.notEqual(await angle(), start);
    await page.screenshot({ path: path.join(process.env.TEMP, 'chartflow-avatar-glow.png') });
    await page.locator('.user-chip').click();
    await page.locator('[data-account="new-user"]').click();
    await page.locator('#dialog [name="name"]').fill('New player');
    await page.locator('#dialog [value="confirm"]').click();
    await page.waitForFunction(() => CF.progress.profile.name === 'New player');
    assert.equal(await page.locator('.all-achievements').count(), 0);
    assert.equal(await page.locator('#user-avatar img').count(), 0);
    await page.locator('#profile-switch').selectOption('local-player');
    await page.waitForSelector('.user-chip.all-achievements #user-avatar img');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.waitForTimeout(600);
    await page.screenshot({ path: path.join(process.env.TEMP, 'chartflow-avatar-mobile.png') });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.emulateMedia({ reducedMotion: 'reduce' });
    assert.equal(await page.locator('.user-chip').evaluate(e => getComputedStyle(e, '::after').animationName), 'none');
    await page.getByRole('button', { name: 'Avatar options', exact: true }).click();
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#avatar-options').isVisible(), false);
    await page.getByRole('button', { name: 'Avatar options', exact: true }).click();
    await page.locator('[data-account="reset-avatar"]').click();
    await page.waitForFunction(() => !CF.progress.profile.avatar);
    assert.equal(await page.locator('#user-avatar img').count(), 0);
    assert.equal(await page.locator('.profile-monogram').innerText(), 'P');
    const heights = await page.locator('.profile-actions > *').evaluateAll(els => els.map(e => e.getBoundingClientRect().height));
    assert.ok(heights.every(h => h === heights[0]), JSON.stringify(heights));
    await page.reload();
    await page.waitForFunction(() => CF.progress.profile);
    assert.equal(await page.evaluate(() => !!CF.progress.profile.avatar), false);
    assert.deepEqual(errors, []);
    console.log('PASS: local avatar upload, borderless images, persistence/import, exact full achievement unlock, animated rays, profile isolation, mobile layout and reduced motion.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
